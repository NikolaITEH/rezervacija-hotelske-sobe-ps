    private void validateLogin(String korisnickoIme, String sifra) throws ValidationException {
        Validator.startValidation().validateNotNullOrEmpty(korisnickoIme, "Morate uneti korisnicko ime!")
                .validateNotNullOrEmpty(sifra, "Morate uneti sifru!")
                .validateStringLength(sifra, "Sifra mora imati vise od 4 karaktera!", 5, null)
                .throwIfInvalid();
    }
