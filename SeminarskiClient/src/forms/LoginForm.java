    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String korisnickoIme = txtKorisnickoIme.getText().trim();
        String sifra = new String(pwSifra.getPassword());
        try {
            validateLogin(korisnickoIme, sifra);
            Recepcioner r = Controller.getInstance().prijaviRecepcioner(korisnickoIme, sifra);
            JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra su ispravni", "Uspesno prijavljivanje", JOptionPane.INFORMATION_MESSAGE);
            Controller.getInstance().setUlogovanRecepcioner(r);
            this.dispose();
            new MainForm().setVisible(true);
        } catch (ValidationException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska pri unosu", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            if (ex.getMessage().equals("Pogresno korisnicko ime ili sifra")) {
                JOptionPane.showMessageDialog(this, "Korisnicko ime i sifra nisu ispravni", "Greska", JOptionPane.ERROR_MESSAGE);
            } else if (ex.getMessage().equals("Recepcioner je vec ulogovan na drugom uredjaju")) {
                JOptionPane.showMessageDialog(this, "Korisnik je vec prijavljen na drugom uredjaju", "Greska", JOptionPane.ERROR_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "Ne moze da se otvori glavna forma i meni", "Greska", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

