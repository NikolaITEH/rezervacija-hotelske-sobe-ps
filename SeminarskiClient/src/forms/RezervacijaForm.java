    private void btnIzmeniStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniStavkuActionPerformed
        if (tblStavke.getSelectedRow() == -1) {
            JOptionPane.showMessageDialog(this, "Morate odabrati stavku iz tabele", "Greska", JOptionPane.WARNING_MESSAGE);
            return;
        }
        try {
            validateStavkaRezervacije();
            StavkaRezervacije sr = tableModelStavkaRezervacije.getStavkaRezervacijeAt(tblStavke.getSelectedRow());
            sr.setBrojDana(Integer.parseInt(txtBrojDana.getText().trim()));
            sr.setBrojGostiju(Integer.parseInt(txtBrojGostiju.getText().trim()));
            sr.setDatumPocetka(dateFormat.parse(txtDatumPocetka.getText().trim()));
            sr.setDatumIsteka(dateFormat.parse(txtDatumIsteka.getText().trim()));
            sr.setIznosPoGostu(Double.parseDouble(txtIznosPoGostu.getText().trim()));
            sr.setIznos(Double.parseDouble(txtIznos.getText().trim()));
            sr.setSoba((Soba) cbSoba.getSelectedItem());
            tableModelStavkaRezervacije.updateStavkaRezervacije(tblStavke.getSelectedRow(), sr);
            txtUkupanIznos.setText(String.format("%.2f", tableModelStavkaRezervacije.getUkupanIznos()));

            txtDatumPocetka.setText("");
            txtDatumIsteka.setText("");
            txtBrojDana.setText("");
            txtBrojGostiju.setText("");
            txtIznosPoGostu.setText("");
            txtIznos.setText("");
            cbSoba.setSelectedIndex(-1);
            tblStavke.clearSelection();
        } catch (ValidationException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska pri unosu podataka", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            Logger.getLogger(RezervacijaForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnIzmeniStavkuActionPerformed

    private void tblStavkeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblStavkeMouseClicked
        if (tblStavke.getModel() == tableModelStavkaRezervacije) {
            int row = tblStavke.getSelectedRow();
            if (row == -1) {
                return;
            }
            StavkaRezervacije sr = tableModelStavkaRezervacije.getStavkaRezervacijeAt(row);
            txtDatumPocetka.setText(dateFormat.format(sr.getDatumPocetka()));
            txtDatumIsteka.setText(dateFormat.format(sr.getDatumIsteka()));
            txtBrojDana.setText(String.valueOf(sr.getBrojDana()));
            txtBrojGostiju.setText(String.valueOf(sr.getBrojGostiju()));
            txtIznosPoGostu.setText(String.format(".2f", sr.getIznosPoGostu()));
            txtIznos.setText(String.format(".2f", sr.getIznos()));
            cbSoba.setSelectedItem(sr.getSoba());
        }
    }//GEN-LAST:event_tblStavkeMouseClicked

