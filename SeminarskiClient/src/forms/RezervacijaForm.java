    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed
        try {
            validateStavkaRezervacije();
            StavkaRezervacije sr = new StavkaRezervacije();
            sr.setBrojDana(Integer.parseInt(txtBrojDana.getText().trim()));
            sr.setBrojGostiju(Integer.parseInt(txtBrojGostiju.getText().trim()));
            sr.setDatumPocetka(dateFormat.parse(txtDatumPocetka.getText().trim()));
            sr.setDatumIsteka(dateFormat.parse(txtDatumIsteka.getText().trim()));
            sr.setSoba((Soba) cbSoba.getSelectedItem());
            sr.setIznos(Double.parseDouble(txtIznos.getText().trim()));
            sr.setIznosPoGostu(Double.parseDouble(txtIznosPoGostu.getText().trim()));
            sr.setRezervacija(rezervacija);
            tableModelStavkaRezervacije.addStavkaRezervacije(sr);
            txtUkupanIznos.setText(String.format("%.2f", tableModelStavkaRezervacije.getUkupanIznos()));
            btnObrisiStavku.setEnabled(true);
            btnIzmeniStavku.setEnabled(true);
            txtDatumPocetka.setText("");
            txtDatumIsteka.setText("");
            txtBrojDana.setText("");
            txtBrojGostiju.setText("");
            txtIznosPoGostu.setText("");
            txtIznos.setText("");
            cbSoba.setSelectedIndex(-1);
        } catch (ValidationException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska pri unosu podataka", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            Logger.getLogger(RezervacijaForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

    private void txtDatumPocetkaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtDatumPocetkaKeyReleased
        if (txtBrojDana != null && !(txtBrojDana.getText().trim().isEmpty())) {
            if (checkDatePattern(txtDatumPocetka.getText().trim())) {
                setDatumIsteka();
            }
        }
    }//GEN-LAST:event_txtDatumPocetkaKeyReleased

    private void txtBrojDanaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBrojDanaKeyReleased
        if (checkDatePattern(txtDatumPocetka.getText().trim()) && txtBrojDana != null && !(txtBrojDana.getText().trim().isEmpty())) {
            setDatumIsteka();
        }
        if (cbSoba.getSelectedItem() != null && txtBrojDana != null && !(txtBrojDana.getText().trim().isEmpty())) {
            setIznos();
        }
        if (txtBrojDana == null || txtBrojDana.getText().trim().isEmpty()) {
            txtDatumIsteka.setText("");
            txtIznos.setText("");
            txtIznosPoGostu.setText("");
        }
    }//GEN-LAST:event_txtBrojDanaKeyReleased

    private void txtBrojGostijuKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtBrojGostijuKeyReleased
        if (txtIznos != null && !(txtIznos.getText().trim().isEmpty()) && txtBrojDana != null && !(txtBrojGostiju.getText().trim().isEmpty())) {
            int brojGostiju = Integer.parseInt(txtBrojGostiju.getText().trim());
            if (brojGostiju <= 0) {
                txtIznosPoGostu.setText("Greska");
                return;
            }
            double iznos = Double.parseDouble(txtIznos.getText().trim());
            double iznosPoGostu = iznos / brojGostiju;
            txtIznosPoGostu.setText(String.format("%.2f", iznosPoGostu));
        }
        if (txtBrojGostiju.getText().trim().isEmpty()) {
            txtIznosPoGostu.setText("");
        }
    }//GEN-LAST:event_txtBrojGostijuKeyReleased

