    private void btn1Search() {
        try {
            List<Rezervacija> rezervacije;
            rezervacija = new Rezervacija();
            if (rbRezervacija.isSelected()) {
                if (!txtUkupanIznos.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateDoubleGreaterThan(txtUkupanIznos.getText().trim(), "Uneti ukupan iznos mora biti veci od 0", 0.1)
                            .throwIfInvalid();
                    rezervacija.setUkupanIznos(Double.parseDouble(txtUkupanIznos.getText().trim()));
                }
                if (!txtDatum.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateDateFormat(txtDatum.getText().trim(), "Uneti datum mora biti u formatu 'dd.MM.yyyy'", "dd.MM.yyyy")
                            .throwIfInvalid();
                    rezervacija.setDatum(dateFormat.parse(txtDatum.getText().trim()));
                }
                rezervacija.setNacinPlacanja(txtNacinPlacanja.getText().trim());
                rezervacija.setNacinRezervisanja(txtNacinRezervisanja.getText().trim());
                rezervacija.setRecepcioner((Recepcioner) cbRecepcioner.getSelectedItem());
                rezervacija.setGost((Gost) cbGost.getSelectedItem());
                rezervacije = Controller.getInstance().vratiListuRezervacija(rezervacija);
                tableModelRezervacija = new TableModelRezervacija(rezervacije);
            } else if (rbGost.isSelected()) {
                if (!txtNacinRezervisanja.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateStringLength(txtNacinRezervisanja.getText().trim(), "Uneti broj gosta mora imati izmedju 8 i 14 karaktera", 8, 14)
                            .throwIfInvalid();
                }
                if (!txtUkupanIznos.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateStringContains(txtUkupanIznos.getText().trim(), "Uneti email gosta mora da sadrzi '@'", "@")
                            .throwIfInvalid();
                }
                if (cbDrzava.getSelectedIndex() != -1) {
                    Validator.startValidation()
                            .validateNotNull(cbDrzava.getSelectedItem(), "Morate izabrati drzavu")
                            .throwIfInvalid();
                }
                Gost gost = new Gost();
                gost.setIme(txtNacinPlacanja.getText().trim());
                gost.setPrezime(txtDatum.getText().trim());
                gost.setBroj(txtNacinRezervisanja.getText().trim());
                gost.setEmail(txtUkupanIznos.getText().trim());
                gost.setDrzava((Drzava) cbDrzava.getSelectedItem());
                rezervacije = Controller.getInstance().vratiListuRezervacija(gost);
                tableModelRezervacija = new TableModelRezervacija(rezervacije);
            } else if (rbRecepcioner.isSelected()) {
                if (!txtNacinRezervisanja.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateStringLength(txtNacinRezervisanja.getText().trim(), "Uneti broj recepcionera mora imati izmedju 8 i 14 karaktera", 8, 14)
                            .throwIfInvalid();
                }
                if (!txtUkupanIznos.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateStringContains(txtUkupanIznos.getText().trim(), "Uneti email recepcionera mora da sadrzi '@'", "@")
                            .throwIfInvalid();
                }
                Recepcioner r = new Recepcioner();
                r.setIme(txtNacinPlacanja.getText().trim());
                r.setPrezime(txtDatum.getText().trim());
                r.setBroj(txtNacinRezervisanja.getText().trim());
                r.setEmail(txtUkupanIznos.getText().trim());
                r.setKorisnickoIme(txtExtra.getText().trim());
                rezervacije = Controller.getInstance().vratiListuRezervacija(r);
                tableModelRezervacija = new TableModelRezervacija(rezervacije);
            } else {
                if (!txtNacinPlacanja.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateStringLength(txtNacinPlacanja.getText().trim(), "Uneti broj sobe mora imati bar 1 karakter", 1, null)
                            .throwIfInvalid();
                }
                if (!txtDatum.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateIntGreaterThan(txtDatum.getText().trim(), "Uneti broj kreveta mora biti veci od 0", 1)
                            .validateIntLowerThan(txtDatum.getText().trim(), "Uneti broj kreveta mora biti manji od 10", 9)
                            .throwIfInvalid();
                }
                if (!txtNacinRezervisanja.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateIntGreaterThan(txtNacinRezervisanja.getText().trim(), "Uneti sprat sobe mora biti veci ili jednak od 0", 0)
                            .throwIfInvalid();
                }
                if (!txtUkupanIznos.getText().trim().isEmpty()) {
                    Validator.startValidation()
                            .validateDoubleGreaterThan(txtUkupanIznos.getText().trim(), "Uneta cena po danu mora biti veca od 0", 0.1)
                            .throwIfInvalid();
                }
                Soba s = new Soba();
                s.setBroj(txtNacinPlacanja.getText().trim());
                if (!txtDatum.getText().trim().isEmpty()) {
                    s.setBrojKreveta(Integer.parseInt(txtDatum.getText().trim()));
                }
                if (!txtNacinRezervisanja.getText().trim().isEmpty()) {
                    s.setSprat(Integer.parseInt(txtNacinRezervisanja.getText().trim()));
                }else{
                    s.setSprat(-1);
                }
                s.setBalkon(checkboxBalkon.isSelected());
                if (!txtUkupanIznos.getText().trim().isEmpty()) {
                    s.setCenaPoDanu(Double.parseDouble(txtUkupanIznos.getText().trim()));
                }
                rezervacije = Controller.getInstance().vratiListuRezervacija(s);
                tableModelRezervacija = new TableModelRezervacija(rezervacije);
            }
            if (rezervacije.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Ne postoji rezervacija koja odgovara unetim kriterijumima", "Nema pronadjenih rezervacija", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            JOptionPane.showMessageDialog(this, "Sistem je nasao rezervacije po zadatim kriterijumima", "Uspesno pronadjene rezervacije", JOptionPane.INFORMATION_MESSAGE);
            tblStavke.setModel(tableModelRezervacija);
            jScrollPane1.setVisible(true);
            tblStavke.setVisible(true);
            this.pack();
            btnZapamtiRez.setEnabled(true);

        } catch (ValidationException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Pogresno unete vrednosti", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje rezervacije po zadatim kriterijumima", "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }

