    private void prepareForm() throws Exception {
        fillCbRecepcioner();
        fillCbGost();
        fillCbSoba();
        switch (mode) {
            case ADD:
                prepareAdd();
                break;
            case SEARCH:
                prepareSearch();
                fillCbDrzava();
                break;
            case VIEW:
                prepareView();
                break;
            default:
                throw new AssertionError();
        }
    }

    private void fillCbRecepcioner() throws Exception {
        cbRecepcioner.removeAllItems();
        List<Recepcioner> recepcioneri = Controller.getInstance().vratiListuSvihRecepcionera();
        for (Recepcioner recepcioner : recepcioneri) {
            cbRecepcioner.addItem(recepcioner);
        }
        cbRecepcioner.setSelectedIndex(-1);
    }

    private void fillCbGost() throws Exception {
        cbGost.removeAllItems();
        List<Gost> gosti = Controller.getInstance().vratiListuSvihGostiju();
        for (Gost gost : gosti) {
            cbGost.addItem(gost);
        }
        cbGost.setSelectedIndex(-1);
    }

    private void fillCbSoba() throws Exception {
        cbSoba.removeAllItems();
        List<Soba> sobe = Controller.getInstance().vratiListuSvihSoba();
        for (Soba soba : sobe) {
            cbSoba.addItem(soba);
        }
        cbSoba.setSelectedIndex(-1);
    }

