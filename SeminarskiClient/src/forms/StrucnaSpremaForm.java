    private void btnZapamtiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnZapamtiActionPerformed
        try {
            validateStrucnaSprema();
            StrucnaSprema s = new StrucnaSprema();
            s = Controller.getInstance().ubaciStrucnaSprema(s);
            s.setNaziv(txtNaziv.getText().trim());
            s.setStepen(txtStepen.getText().trim());
            s.setInstitucija(txtInstitucija.getText().trim());
            Controller.getInstance().promeniStrucnaSprema(s);
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio strucnu spremu", "Uspesno", JOptionPane.INFORMATION_MESSAGE);
            tableModelStrucnaSprema.addStrucnaSprema(s);
        } catch (ValidationException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Greska pri unosu podataka", JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Sistem ne moze da zapamti strucnu spremu", "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnZapamtiActionPerformed

    private void validateStrucnaSprema() throws ValidationException {
        Validator.startValidation()
                .validateNotNullOrEmpty(txtNaziv.getText(), "Morate uneti naziv!")
                .validateNotNullOrEmpty(txtStepen.getText(), "Morate uneti stepen!")
                .validateStringLength(txtStepen.getText(), "Stepen mora imati manje od 7 karaktera!", null, 6)
                .validateNotNullOrEmpty(txtInstitucija.getText(), "Morate uneti instituciju!")
                .throwIfInvalid();
    }

