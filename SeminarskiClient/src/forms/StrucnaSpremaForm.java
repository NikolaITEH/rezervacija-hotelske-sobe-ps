    private void fillTable() {
        try {
            List<StrucnaSprema> strucneSpreme = Controller.getInstance().vratiListuSvihStrucnihSprema();
            tableModelStrucnaSprema = new TableModelStrucnaSprema(strucneSpreme);
            tblStrucnaSprema.setModel(tableModelStrucnaSprema);
            this.pack();
        } catch (Exception ex) {
            Logger.getLogger(StrucnaSpremaForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
